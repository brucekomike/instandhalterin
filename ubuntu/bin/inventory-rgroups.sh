#!/bin/bash
#
# inventory-rgroups.sh — generate rhosts/<group>.txt from the site inventory.
#
# Why this exists: four places described the same fleet and agreed only by hand,
# so hosts silently fell out of scope (see docs/host-inventory-unification.md).
# The site inventory is ONE FILE PER HOST with key=value fields; the group lists
# that bin/rexec.sh consumes are DERIVED from it, never hand-edited.
#
# The inventory itself is site data and does NOT live in this repo: this is a
# public repository that ships the shape. Point FLEET_INVENTORY at wherever the
# private inventory of record actually lives.
#
# Usage:
#   FLEET_INVENTORY=/path/to/private bin/inventory-rgroups.sh          # write
#   FLEET_INVENTORY=/path/to/private bin/inventory-rgroups.sh --check  # report drift, no write
#
# Field set (only alias and group are required):
#   alias=<ssh alias>        group=<role name>       login_user=<ubuntu|root|…>
#   nat_entry=<entry EIP>    reaches=<network role>  host_kind=<vm|bmi|container>
#   key_class=<operator|operator+machine>           backup=<yes|no>
#   note=<one line>          # emitted on its own comment line above the alias
#
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cfg="${IH_CONFIG:-$here/../../.config/ihconfig}"
[[ -d "$cfg" ]] || cfg="$here"
inventory="${FLEET_INVENTORY:-$HOME/.config/instandhalterin/fleet}"
hosts_dir="$inventory/hosts.d"
out_dir="$cfg/rhosts"
mode="${1:-write}"

[[ -d "$hosts_dir" ]] || {
    echo "inventory-rgroups.sh: no inventory at $hosts_dir" >&2
    echo "  set FLEET_INVENTORY to the private inventory of record, e.g." >&2
    echo "  FLEET_INVENTORY=/path/to/fleet bin/inventory-rgroups.sh" >&2
    exit 1
}

# --- parse every host record into "group<TAB>alias<TAB>note" ------------------
rows="$(mktemp)"
trap 'rm -f "$rows"' EXIT

for f in "$hosts_dir"/*.conf; do
    [[ -f "$f" ]] || continue
    alias="" group="" note=""
    while IFS='=' read -r k v; do
        case "$k" in
            alias) alias="$v" ;;
            group) group="$v" ;;
            note)  note="$v" ;;
        esac
    done < <(tr -d '\r' <"$f")
    if [[ -z "$alias" || -z "$group" ]]; then
        echo "inventory-rgroups.sh: $f is missing alias= or group= -- refusing to guess" >&2
        exit 1
    fi
    # one host in two groups is a bug in the inventory, not a thing to silently merge
    if grep -qF "	$alias	" "$rows"; then
        echo "inventory-rgroups.sh: alias $alias appears in more than one record" >&2
        exit 1
    fi
    printf '%s\t%s\t%s\n' "$group" "$alias" "$note" >>"$rows"
done

[[ -s "$rows" ]] || { echo "inventory-rgroups.sh: inventory has no host records" >&2; exit 1; }

status=0
for group in $(cut -f1 "$rows" | sort -u); do
    out="$out_dir/$group.txt"

    # Defense in depth: rhosts/*.txt is gitignored because it carries host names.
    # Writing one into a TRACKED path would publish site data on the next push,
    # so the generator refuses rather than trusting .gitignore alone.
    if command -v git >/dev/null 2>&1 && git -C "$here/.." ls-files --error-unmatch "$out" >/dev/null 2>&1; then
        echo "inventory-rgroups.sh: REFUSING to write $out -- it is tracked by git." >&2
        echo "  Per-host lists must stay unversioned in this repo. Restore the" >&2
        echo "  rhosts/.gitignore guard and commit the <group>.example instead." >&2
        exit 1
    fi

    body="$(mktemp)"
    {
        printf '# GENERATED by bin/inventory-rgroups.sh from %s -- do not hand-edit.\n' "$hosts_dir"
        printf '# The real list stays gitignored (it names hosts); %s.example is the\n' "$group"
        printf '# committed shape. rexec.sh passes each non-comment line straight to\n'
        printf '# ssh, so notes belong on their own lines above an alias.\n'
        awk -F'\t' -v g="$group" '$1==g && $3!="" {print "# " $3} $1==g {print $2}' "$rows"
    } >"$body"

    if [[ "$mode" == "--check" ]]; then
        if [[ ! -f "$out" ]] || ! cmp -s "$body" "$out"; then
            echo "inventory-rgroups.sh: DRIFT -- $out does not match the inventory"
            status=1
        fi
    else
        cp "$body" "$out"
        echo "inventory-rgroups.sh: wrote $out ($(grep -cv '^#' "$out") hosts)"
    fi
    rm -f "$body"
done

if [[ "$mode" == "--check" && "$status" -eq 0 ]]; then
    echo "inventory-rgroups.sh: in sync ($(wc -l <"$rows") hosts, $(cut -f1 "$rows" | sort -u | wc -l) groups)"
fi
exit "$status"
